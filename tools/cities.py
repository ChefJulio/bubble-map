"""Build BubbleMap's enclosed-city table: Data/Cities.lua.

Ironforge and Undercity are built inside a mountain and underground: the terrain tiles (Data/Tiles.lua)
have only the ground above them. Their streets are the minimap images of the city's own model (WMO
group tiles), placed in the world: this table holds them, so BubbleMap draws the cities as the game's
minimap does, in its own map at any zoom. Design: docs/terrain-map.md ("Cities").

Source: TerrainWorldMap by Dramacydal (MIT, credited in THIRD-PARTY-NOTICES), its Forever data
(Data_Forever/mapdata_wmo_tiles_cities.lua, generated by its scripts/gen_wmo_tiles.js from the game's
files), at the pinned commit below; its hand-kept list of tiles never drawn (mapdata_wmo_tile_toggle.lua)
is applied. Only the two enclosed cities: the other capitals' buildings are in the terrain tiles already.

Each tile is TerrainWorldMap's own {fileID, cx, cy, width, height, yawDeg, z}: centre in "Big"
coordinates (Big X = world Y = UnitPosition's west, Big Y = world X = its north), size in yards, the
angle and height its addon draws with (MapCities.lua follows its drawing exactly). Plus each city's
bounding box (west0, north0, west1, north1) from the tiles' corners.

Usage:
  python tools/cities.py           fetch and write the table
  python tools/cities.py --check   only check the committed table is the one the pin gives
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "Data" / "Cities.lua"
REPO = "Dramacydal/TerrainWorldMap"
COMMIT = "f4634d1cd579ef102feb4d7fd7cb67ace719bb99"
TILES_FILE = "Data_Forever/mapdata_wmo_tiles_cities.lua"
TOGGLE_FILE = "Data_Forever/mapdata_wmo_tile_toggle.lua"
CITIES = {1455: "Ironforge", 1458: "Undercity"}
INSTANCE_MAP = 0  # both on the Eastern Kingdoms' instance map

NUMBER = r"-?[\d.]+(?:e-?\d+)?"
TILE = re.compile(r"\{(\d+), (" + NUMBER + r"), (" + NUMBER + r"), (" + NUMBER + r"), (" + NUMBER + r"), ("
                  + NUMBER + r"), (" + NUMBER + r")((?:, " + NUMBER + r"){8})")


def fetch(path: str) -> str:
  url = f"https://raw.githubusercontent.com/{REPO}/{COMMIT}/{path}"
  return subprocess.run(["curl", "-fsSL", url], check=True, capture_output=True).stdout.decode("utf-8")


def hidden_tiles(toggle: str) -> set[tuple[str, int]]:
  """(group, fileID) pairs TerrainWorldMap never draws on the Eastern Kingdoms ("Azeroth")."""
  out = set()
  for m in re.finditer(r'\{group = "([^"]+)", name = "[^"]*", maps = \{([^}]*)\}, tiles = \{([^}]*)\}\}', toggle):
    if '"Azeroth"' in m.group(2):
      for tile in re.findall(r"\d+", m.group(3)):
        out.add((m.group(1), int(tile)))
  return out


def city_block(text: str, ui_map: int) -> str:
  start = text.index(f"Twm_CityWMOTiles[{ui_map}] = {{")
  end = text.find("Twm_CityWMOTiles[", start + 10)
  return text[start:end if end > 0 else None]


def build() -> str:
  text, toggle = fetch(TILES_FILE), fetch(TOGGLE_FILE)
  hidden = hidden_tiles(toggle)
  lines = [
    "local _, ns = ...",
    "",
    "-- Generated by tools/cities.py; don't edit. The enclosed cities' minimap images (their model's",
    "-- group tiles): [instance map][UI map] = { box = { west0, north0, west1, north1 }, tiles = { { fileID,",
    "-- centre west, centre north, width, height, yawDeg, z }, ... } }, from TerrainWorldMap (MIT,",
    f"-- {REPO}) at {COMMIT[:12]}.",
    "",
    "ns.Cities = {",
    f'  source = "{REPO}@{COMMIT[:12]}",',
    "  maps = {",
    f"    [{INSTANCE_MAP}] = {{",
  ]
  total = 0
  for ui_map, name in CITIES.items():
    block = city_block(text, ui_map)
    tiles, xs, ys = [], [], []
    for group in re.split(r"\n    \{\n", block)[1:]:
      gid = re.search(r'group_id = "([^"]+)"', group).group(1)
      for m in TILE.finditer(group):
        file_id = int(m.group(1))
        if (gid, file_id) in hidden:
          continue
        values = [float(v) for v in m.groups()[1:7]]
        corners = [float(v) for v in re.findall(NUMBER, m.group(8))]
        xs += corners[0::2]
        ys += corners[1::2]
        tiles.append((file_id, *values))
    if not tiles:
      raise SystemExit(f"cities: no tiles for {name} ({ui_map})")
    tiles.sort(key=lambda t: t[6])  # by height: drawn bottom up
    lines.append(f"      [{ui_map}] = {{  -- {name}, {len(tiles)} tiles")
    lines.append(f"        box = {{ {max(xs):.1f}, {max(ys):.1f}, {min(xs):.1f}, {min(ys):.1f} }},")
    lines.append("        tiles = {")
    for t in tiles:
      lines.append("          { %d, %.2f, %.2f, %.2f, %.2f, %.2f, %.2f }," % t)
    lines.append("        },")
    lines.append("      },")
    total += len(tiles)
    print(f"cities: {name}: {len(tiles)} tiles")
  lines += ["    },", "  },", "}", ""]
  print(f"cities: {total} tiles")
  return "\n".join(lines)


def main() -> int:
  text = build()
  if "--check" in sys.argv[1:]:
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if current != text:
      print(f"cities --check: {OUT.relative_to(ROOT)} is not the table for {COMMIT[:12]}; run tools/cities.py")
      return 1
    print("cities --check: OK")
    return 0
  OUT.write_text(text, encoding="utf-8", newline="\n")
  print(f"cities: wrote {OUT.relative_to(ROOT)} ({len(text) / 1024:.0f} KB)")
  return 0


if __name__ == "__main__":
  sys.exit(main())
